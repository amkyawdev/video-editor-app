import '../../models/subtitle.dart';

/// Writes the ASS script that libass burns into the video. The same style
/// values drive the in-app preview, so what the user styles is what renders.
class AssWriter {
  const AssWriter._();

  static String build(
    SubtitleDocument document, {
    required int canvasWidth,
    required int canvasHeight,
  }) {
    final style = document.style;
    final scale = canvasHeight <= 0 ? 1.0 : canvasHeight / 1080.0;
    final fontSize = (style.fontSize * scale).clamp(8.0, 400.0);
    final marginV = (style.marginVertical / 100 * canvasHeight).round();
    final marginH = (style.marginHorizontal / 100 * canvasWidth).round();
    final alignment = switch (style.alignment) {
      SubtitleAlignment.bottom => 2,
      SubtitleAlignment.center => 5,
      SubtitleAlignment.top => 8,
    };
    final borderStyle = style.hasBackground ? 3 : 1;
    final outlineColor = style.hasBackground
        ? style.backgroundColor
        : style.outlineColor;
    final outlineWidth = style.hasBackground
        ? (style.outlineWidth + 3).clamp(1.0, 20.0)
        : style.outlineWidth;

    final buffer = StringBuffer()
      ..writeln('[Script Info]')
      ..writeln('; Generated by Amkyaw Studio')
      ..writeln('ScriptType: v4.00+')
      ..writeln('WrapStyle: 2')
      ..writeln('ScaledBorderAndShadow: yes')
      ..writeln('YCbCr Matrix: TV.709')
      ..writeln('PlayResX: $canvasWidth')
      ..writeln('PlayResY: $canvasHeight')
      ..writeln()
      ..writeln('[V4+ Styles]')
      ..writeln(
        'Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, '
        'OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, '
        'ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, '
        'Alignment, MarginL, MarginR, MarginV, Encoding',
      )
      ..writeln(
        'Style: Amkyaw,${_fontName(style.fontFamily)},'
        '${fontSize.toStringAsFixed(1)},'
        '${_assColor(style.primaryColor)},'
        '${_assColor(style.primaryColor)},'
        '${_assColor(outlineColor)},'
        '${_assColor(style.shadowColor)},'
        '${style.bold ? -1 : 0},'
        '${style.italic ? -1 : 0},'
        '0,0,100,100,'
        '${style.letterSpacing.toStringAsFixed(1)},'
        '0,$borderStyle,'
        '${outlineWidth.toStringAsFixed(1)},'
        '${style.shadowDepth.toStringAsFixed(1)},'
        '$alignment,$marginH,$marginH,$marginV,1',
      )
      ..writeln()
      ..writeln('[Events]')
      ..writeln(
        'Format: Layer, Start, End, Style, Name, MarginL, MarginR, '
        'MarginV, Effect, Text',
      );

    final cues = List<SubtitleCue>.of(document.cues)
      ..sort((SubtitleCue a, SubtitleCue b) => a.startUs.compareTo(b.startUs));
    for (final cue in cues) {
      final text = cue.text.trim();
      if (text.isEmpty) continue;
      buffer.writeln(
        'Dialogue: 0,${_assTime(cue.start)},${_assTime(cue.end)},Amkyaw,,'
        '0,0,0,,${escapeText(text)}',
      );
    }
    return buffer.toString();
  }

  static String escapeText(String input) {
    final replaced = input
        .replaceAll('\\', r'\\')
        .replaceAll('{', r'\{')
        .replaceAll('}', r'\}')
        .replaceAll('\r\n', '\n')
        .replaceAll('\n', r'\N');
    return replaced;
  }

  /// ASS stores colours as `&HAABBGGRR` with inverted alpha.
  static String _assColor(int argb) {
    final a = (argb >> 24) & 0xFF;
    final r = (argb >> 16) & 0xFF;
    final g = (argb >> 8) & 0xFF;
    final b = argb & 0xFF;
    final assAlpha = 255 - a;
    String hex(int value) => value.toRadixString(16).padLeft(2, '0');
    return '&H${hex(assAlpha)}${hex(b)}${hex(g)}${hex(r)}';
  }

  static String _assTime(Duration d) {
    final total = d.isNegative ? Duration.zero : d;
    final hours = total.inHours;
    final minutes = total.inMinutes.remainder(60);
    final seconds = total.inSeconds.remainder(60);
    final centis = total.inMilliseconds.remainder(1000) ~/ 10;
    return '$hours:${minutes.toString().padLeft(2, '0')}:'
        '${seconds.toString().padLeft(2, '0')}.'
        '${centis.toString().padLeft(2, '0')}';
  }

  static String _fontName(String family) {
    // libass resolves these names inside fontsdir; keep them stable.
    return switch (family) {
      'Inter' => 'Inter',
      'JetBrainsMono' => 'JetBrains Mono',
      _ => 'Noto Sans Myanmar',
    };
  }
}
